import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { SPACECRAFT_LAUNCH_SITE, buildSlsBlock1Dimensions } from '../rebuild-v5000/bridgepoint-spacecraft-v1.js';

