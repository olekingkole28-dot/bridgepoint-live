
-- Public-safe parcel lot-coverage and verified municipal zoning lookup.
-- Geometry sources remain individually rights-gated. No owner identity fields are exposed.

create table if not exists automation.municipal_zoning_sources_v1 (
  source_id uuid primary key default gen_random_uuid(),
  jurisdiction_key text not null,
  country_code text not null,
  region_code text,
  municipality text,
  source_name text not null,
  source_url text not null,
  source_format text not null default 'OFFICIAL_API_OR_ORDINANCE',
  official_source boolean not null default false,
  publication_scope text not null default 'OWNER_ONLY',
  rights_status text not null default 'UNREVIEWED',
  automation_enabled boolean not null default false,
  status text not null default 'DISCOVERED',
  source_version text,
  checked_at timestamptz,
  last_success_at timestamptz,
  last_error text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (jurisdiction_key, source_url)
);
create index if not exists municipal_zoning_sources_v1_jurisdiction_idx
  on automation.municipal_zoning_sources_v1 (jurisdiction_key, status);

create table if not exists automation.municipal_zoning_districts_v1 (
  district_id bigint generated by default as identity primary key,
  source_id uuid not null references automation.municipal_zoning_sources_v1(source_id) on delete cascade,
  jurisdiction_key text not null,
  country_code text not null,
  region_code text,
  municipality text,
  zone_code text not null,
  zone_name text,
  geom geometry(Geometry,4326) not null,
  official_source boolean not null default false,
  publication_scope text not null default 'OWNER_ONLY',
  rights_status text not null default 'UNREVIEWED',
  source_name text,
  source_url text,
  ordinance_url text,
  effective_from date,
  effective_to date,
  source_updated_at timestamptz,
  last_verified_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists municipal_zoning_districts_v1_geom_gix
  on automation.municipal_zoning_districts_v1 using gist (geom);
create index if not exists municipal_zoning_districts_v1_zone_idx
  on automation.municipal_zoning_districts_v1 (jurisdiction_key, zone_code, effective_from, effective_to);

create table if not exists automation.municipal_zoning_rules_v1 (
  rule_id bigint generated by default as identity primary key,
  source_id uuid not null references automation.municipal_zoning_sources_v1(source_id) on delete cascade,
  jurisdiction_key text not null,
  country_code text not null,
  region_code text,
  municipality text,
  zone_code text not null,
  rule_type text not null default 'LOT_COVERAGE_MAX',
  max_lot_coverage_pct numeric,
  code_section text,
  code_title text,
  rule_source_url text,
  exact_text_excerpt text,
  official_source boolean not null default false,
  verification_status text not null default 'UNREVIEWED',
  publication_scope text not null default 'OWNER_ONLY',
  rights_status text not null default 'UNREVIEWED',
  effective_from date,
  effective_to date,
  verified_by text,
  verified_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint municipal_zoning_rules_v1_coverage_range
    check (max_lot_coverage_pct is null or (max_lot_coverage_pct >= 0 and max_lot_coverage_pct <= 100))
);
create index if not exists municipal_zoning_rules_v1_zone_idx
  on automation.municipal_zoning_rules_v1
  (jurisdiction_key, zone_code, rule_type, verification_status, effective_from, effective_to);

alter table automation.municipal_zoning_sources_v1 enable row level security;
alter table automation.municipal_zoning_districts_v1 enable row level security;
alter table automation.municipal_zoning_rules_v1 enable row level security;
revoke all on automation.municipal_zoning_sources_v1 from anon, authenticated;
revoke all on automation.municipal_zoning_districts_v1 from anon, authenticated;
