import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const moduleCode=readFileSync(new URL('../rebuild-v5000/bridgepoint-emrf-starlink-global-v2.js',import.meta.url),'utf8');
const emrfCode=readFileSync(new URL('../rebuild-v5000/bridgepoint-emrf-spectrogram-v1.js',import.meta.url),'utf8');
const card=readFileSync(new URL('../rebuild-v5000/bridgepoint-view-v5917.js',import.meta.url),'utf8');
const make=await import('data:text/javascript;charset=utf-8,'+encodeURIComponent(moduleCode));
const now=Date.parse('2026-11-20T06:00:00.000Z');
const row=[44714,'STARLINK-1008',Date.parse('2026-11-19T22:00:01.998Z'),15.70821291,.0002968,53.1439,30.01,12.2828,138.5415,'2019-074B'];
const position=make.propagateStarlinkOmmV2(row,now);
assert.ok(position,'catalog object gives a finite orbital position');
assert.ok(position.altitudeM>200000&&position.altitudeM<1500000);
assert.ok(position.lat>=-90&&position.lat<=90);
assert.ok(position.lon>=-180&&position.lon<=180);
assert.equal(position.id,'44714');
assert.equal(position.modelVariant,'v1.5');
const next=make.propagateStarlinkOmmV2(row,now+60000);
assert.ok(next&&Math.abs(next.lon-position.lon)>.02,'satellite moves over Earth with time');
const v2=make.propagateStarlinkOmmV2([...row.slice(0,9),'2025-123AB'],now);
assert.equal(v2?.modelVariant,'v2-mini','newer launch uses dimension-scaled V2 Mini representative model');
const stale=make.propagateStarlinkOmmV2(row,now+10*86400000);
assert.equal(stale,null,'stale orbital records are rejected rather than showing fake current orbits');
const invalid=make.propagateStarlinkOmmV2([44714,'STARLINK',null,15.5,0,53,10,5,15],now);
assert.equal(invalid,null);
const objs=Array.from({length:10500},(_,i)=>[60000+i,'STARLINK-'+i,row[2],15.5,.0001,53,i%360,8,(i*.7)%360,'2025-145AA']);
const subset=make.selectStarlinkCatalogV2(objs,4200);
assert.equal(subset.length,4200,'thousands from genuine catalog, no 28 satellite cap');
assert.equal(new Set(subset.map(x=>x[0])).size,4200);
assert.ok(subset[0]===objs[0]&&subset.at(-1)===objs[Math.floor(4199*10500/4200)]);
assert.ok(moduleCode.includes("MAX_BEAMS=4200"));
assert.ok(moduleCode.includes("new T.InstancedMesh"));
assert.ok(moduleCode.includes("new T.CylinderGeometry"));
assert.ok(moduleCode.includes("new T.BoxGeometry(busLength"));
assert.ok(moduleCode.includes("new T.BoxGeometry(panelLength"));
assert.ok(moduleCode.includes("const beam=state.beams"));
assert.ok(moduleCode.includes("map.transform?.getMatrixForModel"));
assert.ok(moduleCode.includes("CelesTrak OMM"),"real public OMM source and approximate propagation must be disclosed");
assert.ok(moduleCode.includes("NOT original SpaceX CAD")||moduleCode.includes("not SpaceX CAD")||moduleCode.includes("NOT operator telemetry"));
assert.ok(!/Math.random\(/.test(moduleCode),'no synthetic satellite positions');
assert.ok(moduleCode.includes("Date.now()-at>7*86400000"),'expired source must not be passed off as current');
assert.ok(emrfCode.includes("enableStarlinkThousandsV2"));
assert.ok(emrfCode.includes("void enableStarlinkThousandsV2();"));
assert.ok(emrfCode.includes("Number(map.getZoom?.()||0)>=7"),'no global Overpass query at whole Earth zoom');
assert.ok(!emrfCode.includes("setTimeout(end,8000)"),'no eight-second wait to show EM/RF');
assert.ok(card.includes("v=3-emrf-model-orbit-ground"));
assert.ok(card.includes("window.__BP_EMRF_CATALOG_WARMED_V2__"));
assert.ok(moduleCode.includes("starlinkDecal"),'single shared detailed solar and STARLINK textures for instanced satellites');
assert.ok(moduleCode.includes("onSatelliteClick"),'satellite model click shows NORAD details');
assert.ok(moduleCode.includes("state.pickCenters"),'satellite picking must not do thousands of transformations on every map click');
assert.ok(moduleCode.includes("rebuildOrbitPaths"),'faint actual propagated 3D orbital trails');
assert.ok(moduleCode.includes("const boost=clamp("),'continuous zoom size avoids level-of-detail jumps');
assert.ok(moduleCode.includes("getFootprints(max="),'same-source ground signal envelopes');
assert.ok(emrfCode.includes("groundHeat")&&emrfCode.includes("paintGlobalGround"),'modeled global ground color comes from source orbital footprints');
assert.ok(emrfCode.includes("towerShaft")&&emrfCode.includes("towerLegs"),'polygon 3D tower parts are anchored');
assert.ok(emrfCode.includes("safeHeight(p.Strucht)"),'recorded FCC structure height used when present');
